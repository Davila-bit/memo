#!/usr/bin/env node
// Turns the axe scans from the last e2e run (e2e/.results/axe.jsonl, written by expectAccessible)
// into docs/ACCESSIBILITY.md.
//   pnpm e2e && pnpm a11y:report                 → writes ../docs/ACCESSIBILITY.md
//   pnpm a11y:report --out some/other/file.md    → writes there instead (CI artifact)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? path.resolve(process.cwd(), args[i + 1]) : fallback;
};
const IN = opt("--in", path.join(WEB, "e2e", ".results", "axe.jsonl"));
const OUT = opt("--out", path.join(WEB, "..", "docs", "ACCESSIBILITY.md"));

if (!fs.existsSync(IN)) {
  console.error(`[a11y] no scans found at ${path.relative(process.cwd(), IN)}. Run \`pnpm e2e\` first.`);
  process.exit(1);
}

/** @type {Array<{state:string,project:string,viewport:{width:number,height:number}|null,path:string,counts:Record<string,number>,violations:{id:string,impact:string|null,nodes:number}[],rules_passed:number,axe_version:string,at:string}>} */
const scans = fs
  .readFileSync(IN, "utf8")
  .split("\n")
  .filter(Boolean)
  .map((l) => JSON.parse(l));
if (scans.length === 0) {
  console.error("[a11y] the scan log is empty. Run `pnpm e2e` first.");
  process.exit(1);
}

const IMPACTS = ["critical", "serious", "moderate", "minor"];
const projects = [...new Set(scans.map((s) => s.project))].sort((a, b) => (a === "phone" ? -1 : b === "phone" ? 1 : a.localeCompare(b)));
const viewport = Object.fromEntries(projects.map((p) => [p, scans.find((s) => s.project === p)?.viewport]));
const states = [...new Set(scans.map((s) => s.state))];
const pick = (state, project) => scans.filter((s) => s.state === state && s.project === project).at(-1);

const totals = Object.fromEntries(IMPACTS.map((k) => [k, scans.reduce((t, s) => t + (s.counts[k] ?? 0), 0)]));
const versions = [...new Set(scans.map((s) => s.axe_version))].join(", ");
const last = scans.map((s) => s.at).sort().at(-1);
const date = new Date(last).toISOString().slice(0, 10);

const cell = (s) => {
  if (!s) return "not scanned";
  const found = IMPACTS.filter((k) => s.counts[k] > 0).map((k) => `${s.counts[k]} ${k}`);
  const ids = s.violations.map((v) => `\`${v.id}\``).join(", ");
  return found.length === 0
    ? `✓ No violations · ${s.rules_passed} rules passed`
    : `✗ ${found.join(", ")} (${ids}) · ${s.rules_passed} rules passed`;
};
const vp = (p) => (viewport[p] ? `${viewport[p].width}×${viewport[p].height}` : "");

const rows = states.map((state) => {
  const any = scans.find((s) => s.state === state);
  return `| ${state} | \`${any.path}\` | ${projects.map((p) => cell(pick(state, p))).join(" | ")} |`;
});

const totalLine =
  IMPACTS.every((k) => totals[k] === 0)
    ? "**0 violations** of any impact"
    : IMPACTS.map((k) => `${totals[k]} ${k}`).join(", ");

const md = `# Accessibility report

_Generated by \`pnpm a11y:report\` from the axe scans of the last \`pnpm e2e\` run on ${date}. Do not edit by hand: re-run the tests and the script._

This covers **Sarah's web app** (\`web/\`), the part a person operates. Margaret's side has no screen to operate: the kitchen iPad answers by itself and the helper speaks, shows her own mug, and listens.

## Automated: axe-core in every browser test

- **Engine:** axe-core ${versions} via \`@axe-core/playwright\`, in Chromium, against the app in mock mode (no keys, no backend).
- **Rules:** WCAG 2.0, 2.1 and 2.2 level A and AA, plus axe best practices.
- **Gate:** the e2e run fails on any serious or critical violation. Every finding of any impact, including minor and moderate ones, is listed in the table below rather than hidden.
- **Sizes:** ${projects.map((p) => `${p} ${vp(p)}`).join(" and ")} (CSS px).
- **Result:** ${scans.length} scans of ${states.length} pages and states: ${totalLine}.

| State | Page | ${projects.map((p) => `${p[0].toUpperCase()}${p.slice(1)} (${vp(p)})`).join(" | ")} |
|---|---|${projects.map(() => "---").join("|")}|
${rows.join("\n")}

Automated checks find only part of what WCAG asks for. "No violations" here means axe found nothing it can test for; it does not mean the app conforms to WCAG 2.2 AA.

## Checked beyond axe (scripted in \`web/e2e/\`)

These run on every CI build; none of them was a separate manual review.

- **Keyboard only, main flow** (\`today.spec.ts\`, laptop size): sign in, the skip link is the first Tab stop and is visible, Tab to "Check on her now", start a check-in from the sheet, see the result. Not run at phone size.
- **Form errors** (\`today.spec.ts\`): a wrong passcode shows an error that is tied to the field with \`aria-describedby\` and marks it \`aria-invalid\`.
- **Larger text setting** (\`today.spec.ts\`): turning it on is scanned again by axe on Settings and Today.
- **Week chart** (\`week.spec.ts\`): Tab reaches each day's bar, and each bar has a sentence with its day and amount; the same numbers are also in a table.
- **Delete dialog** (\`privacy.spec.ts\`): opened from the keyboard, the destructive button is not the first focus, Escape cancels, and focus goes back to the button that opened it.
- **Colour contrast of the palette** (\`web/scripts/contrast.py\`): text uses the darker \`*-ink\` colours, which pass 4.5:1 on every background they are used on.
- **Status is never colour alone:** a design rule (icon + word + colour, \`StatusBadge\`), checked by the text assertions in the specs, not by a separate audit.
- **Reflow, WCAG 1.4.10** (\`a11y-extra.spec.ts\`): no horizontal scrolling at 320 px and 640 px wide on seven pages (login, Today, Week, Schedule, Ask, Privacy, Setup), with a full-page screenshot of each. The 640 px width stands in for 200% zoom of a 1280 px window. This is an emulated viewport in Chromium, not browser zoom on a real device, and it checks page width, not that every dialog reflows.
- **Reduced motion, WCAG 2.3.3** (\`a11y-extra.spec.ts\`): with \`prefers-reduced-motion: reduce\` emulated, a practice check-in runs from start to result, and at six points on the way no running animation lasts longer than 200 ms or loops forever. The same test without the setting does catch the pulse and the 300 ms entrances, so it is measuring something. It only covers Today and the check-in flow.
- **Keyboard on every page, WCAG 2.1.1 and 2.4.7** (\`a11y-extra.spec.ts\`, laptop size): on Week, Schedule, Privacy and Setup, Tab through the whole page once; every stop must be visible and show a focus outline or ring. On Schedule, a new check-in is added with only Tab, Enter and typing (label and time) and appears in the list. Ask is not in this check yet (it was being rebuilt), and dialogs are covered only where a spec above opens them.

## Not done yet

- **No screen-reader pass** with VoiceOver, TalkBack or NVDA has been done.
- **No real devices:** phone size is emulated in desktop Chromium. Safari and Firefox are not tested.
- **Keyboard on Ask** has not been walked through Tab by Tab, and no page has been checked for focus being hidden behind the fixed bottom bar on a phone (WCAG 2.4.11).
- **Not tested:** real browser zoom, Windows forced colours (high contrast), voice control.
- **No testing with older adults or carers** using the app.
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md);
console.log(`[a11y] ${scans.length} scans, ${states.length} states → ${path.relative(process.cwd(), OUT)}`);
